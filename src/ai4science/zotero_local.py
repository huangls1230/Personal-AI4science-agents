"""Bounded Zotero Desktop local reads. No library writes, credentials or remote URLs.

Returned data is untrusted. Item keys and local library identifiers are distinct
from Better BibTeX citation keys. Exports are generated by Zotero itself.
"""
from __future__ import annotations

import json
import re
from urllib.error import HTTPError, URLError
from urllib.parse import urlencode
from urllib.request import HTTPRedirectHandler, ProxyHandler, Request, build_opener

_BASE = 'http://127.0.0.1:23119'
_MAX_BODY = 2_000_000
_KEY = re.compile(r'^[23456789ABCDEFGHIJKLMNPQRSTUVWXYZ]{8}$')
_STYLE = re.compile(r'^[a-zA-Z0-9][a-zA-Z0-9_-]{0,159}$')


class ZoteroError(Exception):
    """Sanitized failure; server response bodies and credentials are not exposed."""
    def __init__(self, code, message, http_status=None):
        super().__init__(message)
        self.code = code
        self.http_status = http_status


class _NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def _transport(path, method='GET', payload=None, timeout=5):
    headers = {'Accept': 'application/json', 'Zotero-API-Version': '3',
               'User-Agent': 'PersonalAI4Science/0.1'}
    if payload is not None:
        headers['Content-Type'] = 'application/json'
        headers['Zotero-Allowed-Request'] = 'true'
    request = Request(_BASE + path, data=payload, headers=headers, method=method)
    try:
        # Ignore proxy environment variables and forbid redirects, including file URLs.
        with build_opener(ProxyHandler({}), _NoRedirect()).open(request, timeout=timeout) as response:
            body = response.read(_MAX_BODY + 1)
            headers_out = dict(response.headers.items())
            status = response.status
    except HTTPError as exc:
        code = 'not_found' if exc.code == 404 else 'forbidden' if exc.code == 403 else 'http_error'
        raise ZoteroError(code, f'Local Zotero returned HTTP {exc.code}', exc.code) from None
    except (URLError, TimeoutError, OSError):
        raise ZoteroError('unavailable', 'Local Zotero endpoint unavailable or timed out') from None
    if len(body) > _MAX_BODY:
        raise ZoteroError('response_too_large', 'Local response exceeds byte limit')
    return status, headers_out, body


def _library(library_id, library_kind):
    if library_kind not in ('users', 'groups') or isinstance(library_id, bool) or not isinstance(library_id, int) or library_id < 0:
        raise ValueError('library must be users or groups with a non-negative numeric ID')
    if library_kind == 'groups' and library_id == 0:
        raise ValueError('group ID must be positive')
    return f'/api/{library_kind}/{library_id}'


def _key(key):
    if not isinstance(key, str) or not _KEY.fullmatch(key):
        raise ValueError('invalid Zotero item key')
    return key


def _page(limit, start):
    if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= 100:
        raise ValueError('limit must be an integer between 1 and 100')
    if isinstance(start, bool) or not isinstance(start, int) or start < 0:
        raise ValueError('start must be a non-negative integer')
    return {'limit': limit, 'start': start}


def _json(body):
    try:
        return json.loads(body)
    except (UnicodeDecodeError, json.JSONDecodeError):
        raise ZoteroError('invalid_response', 'Local Zotero returned invalid JSON') from None


def _bib_entry_count(body):
    """Count complete top-level BibTeX entries, rejecting uncertain syntax.

    This verifies count only; it does not establish a mapping to Zotero keys.
    """
    try:
        text = body.decode('utf-8-sig')
    except UnicodeDecodeError:
        raise ZoteroError('invalid_response', 'Zotero BibTeX export is not UTF-8') from None
    pos, count, length = 0, 0, len(text)
    while pos < length:
        if text[pos].isspace():
            pos += 1
            continue
        if text[pos] == '%':
            end = text.find('\n', pos)
            pos = length if end < 0 else end + 1
            continue
        match = re.match(r'@([A-Za-z][A-Za-z0-9_-]*)\s*([\{(])', text[pos:])
        if not match:
            raise ZoteroError('invalid_response', 'Cannot reliably parse Zotero BibTeX export')
        entry_type, opening = match.groups()
        pos += match.end()
        stack = ['}' if opening == '{' else ')']
        quote = False
        quote_braces = 0
        while pos < length and stack:
            char = text[pos]
            if char == '\\':
                pos += 2
                continue
            if quote:
                if char == '{':
                    quote_braces += 1
                elif char == '}' and quote_braces:
                    quote_braces -= 1
                elif char == '"' and quote_braces == 0:
                    quote = False
            elif char == '"':
                quote = True
            elif char == '{':
                stack.append('}')
            elif char == '}':
                if stack[-1] != '}':
                    raise ZoteroError('invalid_response', 'Unbalanced BibTeX export')
                stack.pop()
            elif char == ')' and stack[-1] == ')':
                stack.pop()
            pos += 1
        if stack or quote:
            raise ZoteroError('invalid_response', 'Incomplete BibTeX export')
        if entry_type.lower() not in ('comment', 'preamble', 'string'):
            count += 1
    return count


class ZoteroLocalClient:
    def __init__(self, timeout=5, transport=None):
        if isinstance(timeout, bool) or not isinstance(timeout, (int, float)) or not 0 < timeout <= 60:
            raise ValueError('timeout must be greater than 0 and at most 60 seconds')
        self.timeout = timeout
        self._transport = transport or _transport

    def _request(self, path):
        return self._transport(path, timeout=self.timeout)

    def _get_json(self, path, params=None):
        if params:
            path += '?' + urlencode(params)
        return _json(self._request(path)[2])

    def doctor(self, library_id=0, library_kind='users'):
        prefix = _library(library_id, library_kind)
        result = {'connection': 'local', 'desktop_running': 'unknown', 'api_enabled': 'unknown',
                  'api_version': None, 'server_id': None, 'library_accessible': 'unknown',
                  'write_authorization': 'not_checked', 'errors': []}
        try:
            _, headers, _ = self._request('/api/')
            headers = {k.lower(): v for k, v in headers.items()}
            result.update(desktop_running='reachable', api_enabled=True,
                          api_version=headers.get('zotero-api-version'), server_id=headers.get('zotero-server-id'))
        except ZoteroError as exc:
            if exc.code == 'forbidden':
                result.update(desktop_running='reachable', api_enabled=False)
            result['errors'].append(exc.code)
            return result
        try:
            self._get_json(prefix + '/items', _page(1, 0))
            result['library_accessible'] = True
        except ZoteroError as exc:
            result['library_accessible'] = False
            result['errors'].append(exc.code)
        return result

    def get_item(self, library_id, item_key, *, library_kind='users'):
        return self._get_json(_library(library_id, library_kind) + '/items/' + _key(item_key))

    def list_items(self, library_id=0, *, library_kind='users', limit=20, start=0):
        return self._get_json(_library(library_id, library_kind) + '/items', _page(limit, start))

    def search_items(self, library_id, query, *, library_kind='users', limit=20, start=0, qmode='titleCreatorYear'):
        if not isinstance(query, str) or not query.strip() or len(query) > 500:
            raise ValueError('query must be nonempty text of at most 500 characters')
        if qmode not in ('titleCreatorYear', 'everything'):
            raise ValueError('qmode must be titleCreatorYear or everything')
        return self._get_json(_library(library_id, library_kind) + '/items', {**_page(limit, start), 'q': query, 'qmode': qmode})

    def list_collections(self, library_id=0, *, library_kind='users', limit=20, start=0):
        return self._get_json(_library(library_id, library_kind) + '/collections', _page(limit, start))

    def get_tags(self, library_id=0, *, library_kind='users', limit=20, start=0):
        return self._get_json(_library(library_id, library_kind) + '/tags', _page(limit, start))

    def get_attachments(self, library_id, item_key, *, library_kind='users', limit=20, start=0):
        children = self._get_json(_library(library_id, library_kind) + '/items/' + _key(item_key) + '/children', _page(limit, start))
        if not isinstance(children, list):
            raise ZoteroError('invalid_response', 'Expected children list')
        return [child for child in children if isinstance(child, dict) and isinstance(child.get('data'), dict) and child['data'].get('itemType') == 'attachment']

    def export(self, library_id, item_keys, format, *, library_kind='users', style=None):
        """Export with bounded preflight; counts do not prove entry identities.

        Formatted bibliographies are returned as generated XHTML and are not
        independently checked for entry count or identity. The preflight and
        export are separate requests and can race with concurrent library edits.
        """
        if not isinstance(item_keys, (list, tuple)) or not 1 <= len(item_keys) <= 50:
            raise ValueError('export requires between 1 and 50 item keys')
        keys = [_key(k) for k in item_keys]
        if len(set(keys)) != len(keys):
            raise ValueError('duplicate item keys')
        if format not in ('bibtex', 'biblatex', 'csljson', 'bib'):
            raise ValueError('unsupported export format')
        params = {'itemKey': ','.join(keys), 'format': format}
        if format == 'bib':
            if not isinstance(style, str) or not _STYLE.fullmatch(style):
                raise ValueError('a valid installed CSL style ID is required')
            params['style'] = style
        elif style is not None:
            raise ValueError('style is only valid for formatted bibliography')
        prefix = _library(library_id, library_kind)
        # Check the whole bounded key set before exporting; the API can otherwise
        # return a valid-looking partial bibliography when some keys are missing.
        found = self._get_json(prefix + '/items', {'itemKey': ','.join(keys), 'limit': len(keys), 'start': 0})
        if not isinstance(found, list):
            raise ZoteroError('invalid_response', 'Expected item list during export preflight')
        returned_keys = {item.get('key') for item in found if isinstance(item, dict)}
        if returned_keys != set(keys):
            raise ZoteroError('incomplete_export', 'Some requested item keys were unavailable during export preflight')
        body = self._request(prefix + '/items?' + urlencode(params))[2]
        if not body.strip():
            raise ZoteroError('empty_export', 'Zotero returned an empty export')
        if format == 'csljson':
            records = _json(body)
            if not isinstance(records, list) or len(records) != len(keys):
                raise ZoteroError('incomplete_export', 'CSL JSON count differs from requested items')
        elif format in ('bibtex', 'biblatex') and _bib_entry_count(body) != len(keys):
            raise ZoteroError('incomplete_export', 'BibTeX entry count differs from requested items')
        return body

    def write(self, *args, **kwargs):
        raise ZoteroError('blocked', 'Zotero writes are not implemented; no write was attempted')


class BetterBibTeXAdapter:
    """Read-only JSON-RPC subset; never invokes key regeneration or writes."""
    def __init__(self, timeout=5, transport=None):
        self._client = ZoteroLocalClient(timeout, transport)

    def _rpc(self, method, params):
        if method not in ('api.ready', 'item.citationkey', 'item.export'):
            raise ValueError('unsupported BBT method')
        body = json.dumps({'jsonrpc': '2.0', 'id': 1, 'method': method, 'params': params}).encode()
        _, _, raw = self._client._transport('/better-bibtex/json-rpc', method='POST', payload=body, timeout=self._client.timeout)
        obj = _json(raw)
        if not isinstance(obj, dict) or obj.get('id') != 1 or obj.get('jsonrpc') != '2.0' or 'error' in obj or 'result' not in obj:
            raise ZoteroError('bbt_error', 'Better BibTeX unavailable or returned an RPC error')
        return obj['result']

    def ready(self):
        result = self._rpc('api.ready', [])
        if not isinstance(result, dict) or not isinstance(result.get('betterbibtex'), str) or not isinstance(result.get('zotero'), str):
            raise ZoteroError('invalid_response', 'Invalid Better BibTeX readiness response')
        return result

    def citation_keys(self, library_id, item_keys):
        # BBT uses Zotero's internal libraryID, not the Local API users/0 alias.
        if library_id is not None and (isinstance(library_id, bool) or not isinstance(library_id, int) or library_id <= 0):
            raise ValueError('BBT library ID must be a positive internal ID or None for My Library')
        if not isinstance(item_keys, (list, tuple)) or not 1 <= len(item_keys) <= 50:
            raise ValueError('between 1 and 50 item keys required')
        result = self._rpc('item.citationkey', [[_key(key) if library_id is None else f'{library_id}:{_key(key)}' for key in item_keys]])
        if not isinstance(result, dict):
            raise ZoteroError('invalid_response', 'Invalid Better BibTeX citation key response')
        return result

    def export(self, citation_keys, translator, library_id=None):
        if library_id is not None and (isinstance(library_id, bool) or not isinstance(library_id, int) or library_id <= 0):
            raise ValueError('BBT library ID must be a positive internal ID or None for My Library')
        if not isinstance(citation_keys, (list, tuple)) or not 1 <= len(citation_keys) <= 50 or any(not isinstance(k, str) or not k or len(k) > 200 for k in citation_keys):
            raise ValueError('between 1 and 50 citation keys required')
        if translator not in ('Better BibTeX', 'Better BibLaTeX'):
            raise ValueError('unsupported Better BibTeX translator')
        params = [list(citation_keys), translator]
        if library_id is not None:
            params.append(library_id)
        result = self._rpc('item.export', params)
        if not isinstance(result, str) or not result.strip():
            raise ZoteroError('invalid_response', 'Invalid Better BibTeX export response')
        return result
